/**
 * Тайминги отыгрыша раунда — обычные и турбо.
 *
 * Держим ОДНИМ МЕСТОМ, а не константами внутри DiceScene: турбо обязано менять
 * все три отрезка согласованно, а разбросанные по сцене числа расходятся —
 * ускорили физику, забыли паузу, и кубики улетают раньше, чем игрок увидел
 * комбинацию.
 *
 * Раунд состоит из:
 *   1. физика  — кубики катятся, пока не осядут   (timeScale)
 *   2. пауза   — игрок смотрит на выпавшее        (settleHoldSec)
 *   3. полёт   — кубики уходят в табло статистики (flySec + flyStagger)
 */
export interface DiceTiming {
  /**
   * Множитель скорости ФИЗИКИ. 1 — реальное время (под него подобран бросок),
   * 2 — вдвое быстрее. Ускоряем ВРЕМЯ, а не силу броска: исход уже решён
   * сервером, и трогать импульсы значило бы пересобирать подбор в воркере.
   */
  timeScale: number;
  /** Пауза после оседания, сек. */
  settleHoldSec: number;
  /** Длительность полёта одного кубика в табло, сек. */
  flySec: number;
  /** Задержка между вылетами соседних кубиков, сек. */
  flyStagger: number;
}

/** Обычный режим — то, под что подбиралась физика. */
export const NORMAL_TIMING: DiceTiming = {
  timeScale: 1,
  settleHoldSec: 1.0,
  flySec: 0.75,
  flyStagger: 0.16,
};

/**
 * Турбо: физика вдвое быстрее, паузы урезаны.
 *
 * Бросок остаётся НАСТОЯЩИМ — кубики так же катятся и сталкиваются, просто
 * время идёт быстрее. Это сознательно не «показать сразу результат»: 3D-сцену
 * делали ради физики, и выбрасывать её в турбо значило бы выбрасывать саму игру.
 */
export const TURBO_TIMING: DiceTiming = {
  timeScale: 2,
  settleHoldSec: 0.3,
  flySec: 0.4,
  flyStagger: 0.08,
};

export function timingFor(turbo: boolean): DiceTiming {
  return turbo ? TURBO_TIMING : NORMAL_TIMING;
}

/** Пауза между раундами автобета: кубики должны осесть и улететь. */
export const AUTO_GAP_MS = 900;
/** То же в турбо — сокращается вместе со всем остальным. */
export const AUTO_GAP_TURBO_MS = 300;

/** Пауза автобета под текущий режим. */
export function autoGapMs(turbo: boolean): number {
  return turbo ? AUTO_GAP_TURBO_MS : AUTO_GAP_MS;
}
