import { describe, it, expect } from "vitest";

/**
 * Полёт фишки: приземление привязано к ПУТИ, а не ко времени.
 *
 * Баг, который это ловит: у полёта нелинейный ease, поэтому доля времени НЕ
 * равна доле пути. Сигнал «приземлилась» стоял на 75% ВРЕМЕНИ, а при тогдашнем
 * power2.in фишка проходила к тому моменту лишь 56% пути — постоянная
 * появлялась в зоне, пока летящая была на середине стола, и та растворялась в
 * воздухе, не долетев.
 *
 * Тест проверяет ПРИНЦИП, а не конкретную кривую: при любом нелинейном ease
 * привязка ко времени расходится с путём, поэтому порог обязан считаться по
 * прогрессу t.
 */

/** Доля пути, на которой фишку считаем коснувшейся зоны (LAND_AT в модуле). */
const LAND_AT = 0.9;

/** Кривые, которые полёт использовал: обе нелинейные. */
const EASES: ReadonlyArray<readonly [string, (t: number) => number]> = [
  ["power2.in", (t) => t * t],
  ["power1.inOut", (t) => (t < 0.5 ? 2 * t * t : 1 - 2 * (1 - t) * (1 - t))],
];

describe("траектория полёта фишки", () => {
  it.each(EASES)("%s: время не равно пути — привязка ко времени неверна", (_name, ease) => {
    // Хотя бы в одной точке доля пути заметно расходится с долей времени.
    const diffs = [0.25, 0.5, 0.75].map((t) => Math.abs(ease(t) - t));
    expect(Math.max(...diffs)).toBeGreaterThan(0.05);
  });

  it.each(EASES)("%s: порог по ПУТИ достигается у самой зоны", (_name, ease) => {
    // Ищем момент времени, когда пройдено LAND_AT пути.
    let t = 0;
    while (t < 1 && ease(t) < LAND_AT) t += 0.001;
    // К этому моменту фишка действительно у цели, а не на полпути.
    expect(ease(t)).toBeGreaterThanOrEqual(LAND_AT);
  });

  it("остаток пути после касания короткий — хвост не тянется", () => {
    expect(1 - LAND_AT).toBeLessThanOrEqual(0.15);
  });
});
